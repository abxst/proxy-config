"""Compile a crawl of official docs into the offline app's compact catalog.

Usage: python scripts/build_directive_catalog.py Server_Config_Directive_Inventory.json

The source inventory is generated by crawl_config_docs.py; the resulting
compressed catalog is committed and embedded in ProxyConfig.Core.
"""

from __future__ import annotations

import gzip
import json
import sys
from pathlib import Path


OUTPUT = Path(__file__).resolve().parents[1] / "src/ProxyConfig.Core/Registry/catalog.json.gz"


def build(source: Path) -> bytes:
    inventory = json.loads(source.read_text(encoding="utf-8"))
    entries: list[list[str]] = []
    properties = (
        "syntax",
        "context",
        "default",
        "description",
        "status",
        "override",
        "compatibility",
    )

    for server in ("nginx", "apache"):
        for directive in inventory[server]:
            meta = directive.get("metadata", {})
            entries.append([
                server,
                directive["name"],
                directive["module"],
                *[meta.get(key, "") for key in properties],
                directive["url"],
            ])

    for variable in inventory["nginx_variables"]:
        entries.append([
            "nginx-variable", variable["name"], variable["module"],
            "", "", "", "", "", "", "", variable["url"],
        ])

    payload = {
        "generatedAtUtc": inventory["generated_at_utc"],
        "entries": entries,
    }
    data = json.dumps(payload, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    return gzip.compress(data, compresslevel=9, mtime=0)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("Usage: python scripts/build_directive_catalog.py INVENTORY.json")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(build(Path(sys.argv[1])))
    print(f"Wrote {OUTPUT}: {OUTPUT.stat().st_size:,} bytes")
